// The portfolio's view of the projects: grouped, numbered and linked.
import { PROJECTS, CATEGORIES } from './projects.js';
import MEDIA from './media.json';

/** Projects in portfolio order: by category, then as listed. */
export const WORK = CATEGORIES.flatMap(c => PROJECTS.filter(p => p.work?.category === c.id));

/** A published media file, by its source name in media-src/work (see tools/fingerprint-media.cjs). */
function media(name) {
  const m = MEDIA[name];
  if (!m) throw new Error(`No media "${name}": add it to media-src/work and run npm run media`);
  return m;
}

